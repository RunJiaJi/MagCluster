def generate_html_report(
    clusters: List[MGCCluster],
    scores: Dict[str, ClusterScore],
    out_path: Path
):
    """Generate standalone HTML report."""
    n_genomes = len({c.genome_name for c in clusters})
    n_mgcs = len(clusters)
    n_high = sum(1 for s in scores.values() if s.confidence == "High")

    # Mineral summary
    minerals = [s.mineral_type for s in scores.values()]
    n_mag = minerals.count("Magnetite")
    n_gre = minerals.count("Greigite")
    min_sum_parts = []
    if n_mag: min_sum_parts.append(f"{n_mag} Fe₃O₄")
    if n_gre: min_sum_parts.append(f"{n_gre} Fe₃S₄")
    mineral_summary = " / ".join(min_sum_parts) if min_sum_parts else "None"

    # Cluster rows
    c_rows = []
    for c in clusters:
        s = scores[c.cluster_id]
        conf_cls = "badge-high" if s.confidence == "High" else ("badge-med" if s.confidence == "Medium" else "badge-low")
        min_cls = "badge-mag" if s.mineral_type == "Magnetite" else "badge-gre"
        flags_str = ", ".join(s.flags) if s.flags else "-"
        core_str = ", ".join(s.core_genes_found)

        c_rows.append(f"""
        <tr>
          <td><strong>{c.cluster_id}</strong></td>
          <td>{c.contig_id}</td>
          <td>{c.start_bp:,} - {c.end_bp:,}</td>
          <td>{c.span_bp:,}</td>
          <td><strong>{int(s.completeness_score * 100)}%</strong> ({s.n_core_genes}/10)</td>
          <td><span class="badge {conf_cls}">{s.confidence}</span></td>
          <td><span class="badge {min_cls}">{s.mineral_type}</span></td>
          <td>{s.lineage_signature}</td>
          <td><small>{core_str}</small></td>
          <td><small>{flags_str}</small></td>
        </tr>
        """)

    # Matrix
    m_headers = "".join(f"<th>{f}</th>" for f in CORE_FAMILIES)
    m_rows = []
    for c in clusters:
        s = scores[c.cluster_id]
        cells = []
        for fam in CORE_FAMILIES:
            if fam in s.core_genes_found:
                cells.append('<td class="matrix-cell cell-present">✓</td>')
            else:
                cells.append('<td class="matrix-cell cell-absent">·</td>')
        m_rows.append(f"<tr><td><strong>{c.cluster_id}</strong></td>{''.join(cells)}</tr>")

    html = HTML_TEMPLATE.format(
        n_genomes=n_genomes,
        n_mgcs=n_mgcs,
        n_high=n_high,
        mineral_summary=mineral_summary,
        cluster_rows="\n".join(c_rows) if c_rows else "<tr><td colspan='10'>No MGCs detected.</td></tr>",
        matrix_headers=m_headers,
        matrix_rows="\n".join(m_rows) if m_rows else "<tr><td colspan='11'>No data</td></tr>"
    )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html)
