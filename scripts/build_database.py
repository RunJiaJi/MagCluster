#!/usr/bin/env python3
"""Build curated Magnetosome HMM database and rules configuration from 817-protein reference FASTA.

Handles:
1. Header parsing & validation
2. Exact sequence deduplication within strain
3. Split-gene segregation (MamE/MamO/Man5 full-length vs domain fragments)
4. Singleton & aliased family handling
5. MSA generation via pyfamsa
6. HMM profile construction via pyhmmer
7. Generation of rules.yaml with biological classifications (core/accessory, mineral, lineage, colors)
"""

import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple
import yaml
from Bio import SeqIO
import pyfamsa
import pyhmmer

RULES_HEADER = """# MagCluster built-in rules (generated by scripts/build_database.py).
# Keys actually read by MagCluster: profiles.<name>.parent_family / role / lineage /
# color / trusted_cutoff (the default bit-score cutoff; replaced by -s/--score when
# given), core_families (shown by `magcluster db`), version.
# Informational only, NOT read by `magcluster run`: clustering_params (use --max-gap,
# -th/--min-families and -un/--flank instead; the 25 kb intergenic limit is fixed),
# per-profile evalue_cutoff (the global -e/--evalue option applies), color_palette,
# n_reference_seqs and median_length.
"""

ROOT = Path(__file__).resolve().parent.parent
SRC_DATA = ROOT / "src" / "magcluster" / "data"
HMM_DIR = SRC_DATA / "hmms"
HMM_DIR.mkdir(parents=True, exist_ok=True)

INPUT_FASTA = ROOT.parent / "20251216_representative_817magProteins_MamMmsManMadMcaMaqMaeFeo_JRJ.original.fasta"
if not INPUT_FASTA.exists():
    # Try current directory
    INPUT_FASTA = Path("20251216_representative_817magProteins_MamMmsManMadMcaMaqMaeFeo_JRJ.original.fasta")

HDR_RE = re.compile(
    r"^(?P<id>\S+)\s+(?P<prod>.*?)\s*(?P<acc>\b[A-Z]{2,3}_?\d{5,}\.\d)?\s*\[(?P<strain>[^\]]+)\]\s*$"
)

# Core families definition for MGC identification
CORE_FAMILIES = {
    "MamA", "MamB", "MamE", "MamI", "MamK", "MamL", "MamM", "MamO", "MamP", "MamQ"
}

# Lineage & mineral classification rules
GREIGITE_FAMILIES = {
    "MamA-greigite", "MamB-greigite", "MamE-greigite", "MamE-Nter-greigite", "MamE-Cter-greigite",
    "MamI-4-greigite", "MamI-5-greigite", "MamMB-greigite", "MamO-greigite", "MamP-greigite",
    "MamQ-greigite", "MamT-greigite"
}

COLOR_MAP = {
    "mam": "#E63946",       # Coral Red (Core/classical Mam)
    "mms": "#F4A261",       # Sandy Amber
    "mad": "#2A9D8F",       # Emerald Teal
    "man": "#1D3557",       # Navy Cobalt
    "mae": "#8338EC",       # Purple (Environmental/novel)
    "mca": "#06D6A0",       # Sea green
    "maq": "#FF70A6",       # Pink
    "feo": "#6C757D",       # Neutral Slate Gray (Iron context)
    "greigite": "#B5179E",  # Violet Red for greigite-specific markers
}

def parse_and_clean_records(fasta_path: Path):
    """Parse fasta, deduplicate exact identical seqs in same strain, partition into sub-profiles."""
    records = list(SeqIO.parse(fasta_path, "fasta"))
    print(f"Loaded {len(records)} raw records from {fasta_path.name}")
    
    seen_strain_seq = set()
    cleaned = []
    
    for i, rec in enumerate(records):
        m = HDR_RE.match(rec.description)
        if not m:
            print(f"Warning: could not parse header: {rec.description}")
            continue
        
        prod = m["prod"].strip()
        strain = m["strain"].strip()
        gene_name = re.sub(r"^[Mm]agnetosome protein\s+", "", prod).strip()
        seq_str = str(rec.seq).upper().rstrip("*")
        seq_hash = hashlib.md5(seq_str.encode()).hexdigest()
        
        # Deduplication check
        dedup_key = (strain, gene_name, seq_hash)
        if dedup_key in seen_strain_seq:
            continue
        seen_strain_seq.add(dedup_key)
        
        cleaned.append({
            "rec_id": f"{rec.id}_{i}",
            "gene_name": gene_name,
            "strain": strain,
            "seq": seq_str,
            "length": len(seq_str)
        })
        
    print(f"Retained {len(cleaned)} unique records after strain-level deduplication (removed {len(records) - len(cleaned)} duplicate copies)")
    return cleaned

def assign_profile_name(item: dict) -> Tuple[str, str]:
    """Map a protein to a profile name and parent family.
    
    Splits MamE, MamO, Man5 into domain profiles if needed.
    Aliases FeoA1/FeoA2 -> FeoA, FeoB1 -> FeoB.
    """
    g = item["gene_name"]
    length = item["length"]
    
    # 1. Alias Feo
    if g in ("FeoA", "FeoA1", "FeoA2"):
        return "FeoA", "FeoA"
    if g in ("FeoB", "FeoB1"):
        return "FeoB", "FeoB"
        
    # 2. Greigite variants
    if "greigite" in g:
        if "MamE-Nter" in g: return "MamE_Nter_greigite", "MamE"
        if "MamE-Cter" in g: return "MamE_Cter_greigite", "MamE"
        if "MamE" in g: return "MamE_greigite", "MamE"
        if "MamO" in g: return "MamO_greigite", "MamO"
        if "MamT" in g: return "MamT_greigite", "MamT"
        if "MamP" in g: return "MamP_greigite", "MamP"
        if "MamQ" in g: return "MamQ_greigite", "MamQ"
        if "MamB" in g or "MamMB" in g: return "MamB_greigite", "MamB"
        if "MamA" in g: return "MamA_greigite", "MamA"
        if "MamI" in g: return "MamI_greigite", "MamI"
        
    # 3. MamE partitioning (Full vs Nter vs Cter vs MamEO)
    if g == "MamEO":
        return "MamEO", "MamE"
    if "MamE-Nter" in g:
        return "MamE_Nter", "MamE"
    if "MamE-Cter" in g:
        return "MamE_Cter", "MamE"
    if g.startswith("MamE"):
        # Check length: if length < 350 aa, it is an unflagged Nter or Cter fragment
        if length < 400:
            return "MamE_Nter", "MamE"
        return "MamE_full", "MamE"

    # 4. MamO partitioning
    if "MamO-Cter" in g or "MamO-I" in g or "MamO-II" in g or (g.startswith("MamO") and length < 420):
        return "MamO_domain", "MamO"
    if g.startswith("MamO"):
        return "MamO_full", "MamO"
        
    # 5. Man5 partitioning
    if "Man5-Nter" in g:
        return "Man5_Nter", "Man5"
    if "Man5-Cter" in g:
        return "Man5_Cter", "Man5"
    if g.startswith("Man5"):
        return "Man5_full", "Man5"

    # 6. Standard families (MamK-I, MamK-1 -> MamK)
    fam_match = re.match(r"^(Mam[A-Z]{1,2}|Mms\d+|Mms[A-Z]|Man\d+|Mad\d+|Mca[A-Z]|Maq\d*|Maq[A-Z]|Mae[A-Z]?\d*|Feo[A-Z]\d*)", g, re.I)
    if fam_match:
        base = fam_match.group(1)
        # Normalize casing (e.g., Mms6, MamK)
        base = base[0].upper() + base[1:]
        return base, base
        
    return g, g

def main():
    cleaned_items = parse_and_clean_records(INPUT_FASTA)
    
    # Group by profile name
    profiles_data: Dict[str, List[dict]] = {}
    profile_to_parent: Dict[str, str] = {}
    
    for item in cleaned_items:
        prof_name, parent_fam = assign_profile_name(item)
        profiles_data.setdefault(prof_name, []).append(item)
        profile_to_parent[prof_name] = parent_fam
        
    print(f"Defined {len(profiles_data)} distinct HMM profiles across {len(set(profile_to_parent.values()))} parent families.")
    
    # Build HMMs
    alphabet = pyhmmer.easel.Alphabet.amino()
    builder = pyhmmer.plan7.Builder(alphabet)
    background = pyhmmer.plan7.Background(alphabet)
    
    built_hmms = []
    meta_rows = []
    
    for prof_name in sorted(profiles_data.keys()):
        items = profiles_data[prof_name]
        parent = profile_to_parent[prof_name]
        lens = [it["length"] for it in items]
        med_len = sorted(lens)[len(lens)//2]
        
        meta_rows.append({
            "profile": prof_name,
            "parent_family": parent,
            "n_seqs": len(items),
            "median_length": med_len,
            "min_length": min(lens),
            "max_length": max(lens)
        })
        
        if len(items) == 1:
            # Single sequence profile
            s_name = items[0]["rec_id"].encode()
            s_seq = items[0]["seq"]
            easel_msa = pyhmmer.easel.TextMSA(
                name=prof_name.encode(),
                sequences=[pyhmmer.easel.TextSequence(name=s_name, sequence=s_seq)]
            ).digitize(alphabet)
            hmm, profile, opt = builder.build_msa(easel_msa, background)
            built_hmms.append(hmm)
        else:
            # Multiple sequences: align using pyfamsa
            famsa_seqs = [pyfamsa.Sequence(it["rec_id"].encode(), it["seq"].encode()) for it in items]
            aligner = pyfamsa.Aligner()
            msa = aligner.align(famsa_seqs)
            
            easel_msa = pyhmmer.easel.TextMSA(
                name=prof_name.encode(),
                sequences=[pyhmmer.easel.TextSequence(name=s.id, sequence=s.sequence.decode()) for s in msa]
            ).digitize(alphabet)
            hmm, profile, opt = builder.build_msa(easel_msa, background)
            built_hmms.append(hmm)
            
    # Write HMM library
    hmm_out = HMM_DIR / "magnetosome.hmm"
    with open(hmm_out, "wb") as f:
        for hmm in built_hmms:
            hmm.write(f)
    print(f"Successfully compiled {len(built_hmms)} HMMs into {hmm_out} ({hmm_out.stat().st_size // 1024} KB)")
    
    # Generate rules.yaml
    rules = {
        "version": "1.0.0",
        "clustering_params": {
            "max_intergenic_genes": 5,
            "min_distinct_core": 3,
            "min_distinct_total": 4,
            "min_cluster_span_bp": 2000,
        },
        "core_families": sorted(list(CORE_FAMILIES)),
        "color_palette": COLOR_MAP,
        "profiles": {}
    }
    
    for row in meta_rows:
        prof = row["profile"]
        parent = row["parent_family"]
        is_core = parent in CORE_FAMILIES
        
        # Determine lineage
        prefix = parent[:3].lower()
        if "greigite" in prof.lower():
            lineage = "Desulfo_greigite"
            color = COLOR_MAP["greigite"]
        elif prefix == "mam":
            lineage = "Alpha_classical"
            color = COLOR_MAP["mam"]
        elif prefix == "mms":
            lineage = "Alpha_Mms"
            color = COLOR_MAP["mms"]
        elif prefix == "mad":
            lineage = "Desulfo_Mad"
            color = COLOR_MAP["mad"]
        elif prefix == "man":
            lineage = "Nitrospirota_Man"
            color = COLOR_MAP["man"]
        elif prefix == "mae":
            lineage = "Environmental_Mae"
            color = COLOR_MAP["mae"]
        elif prefix == "mca":
            lineage = "Novel_Mca"
            color = COLOR_MAP["mca"]
        elif prefix == "maq":
            lineage = "Novel_Maq"
            color = COLOR_MAP["maq"]
        elif prefix == "feo":
            lineage = "Iron_context"
            color = COLOR_MAP["feo"]
        else:
            lineage = "Other"
            color = "#A8DADC"
            
        role = "core" if is_core else ("iron_context" if prefix == "feo" else "accessory")
        
        rules["profiles"][prof] = {
            "parent_family": parent,
            "role": role,
            "lineage": lineage,
            "color": color,
            "trusted_cutoff": 25.0,  # bit score cutoff
            "evalue_cutoff": 1e-5,
            "n_reference_seqs": row["n_seqs"],
            "median_length": row["median_length"]
        }
        
    rules_out = SRC_DATA / "rules.yaml"
    with open(rules_out, "w", encoding="utf-8") as f:
        f.write(RULES_HEADER)
        yaml.dump(rules, f, sort_keys=False, allow_unicode=True)
    print(f"Generated rules configuration: {rules_out}")

    # Write summary TSV
    tsv_out = SRC_DATA / "profiles_summary.tsv"
    with open(tsv_out, "w", encoding="utf-8") as f:
        f.write("profile\tparent_family\trole\tlineage\tn_seqs\tmedian_length\tmin_len\tmax_len\n")
        for r in meta_rows:
            p = r["profile"]
            role = rules["profiles"][p]["role"]
            lin = rules["profiles"][p]["lineage"]
            f.write(f"{p}\t{r['parent_family']}\t{role}\t{lin}\t{r['n_seqs']}\t{r['median_length']}\t{r['min_length']}\t{r['max_length']}\n")
    print(f"Saved profile summary: {tsv_out}")

if __name__ == "__main__":
    main()
